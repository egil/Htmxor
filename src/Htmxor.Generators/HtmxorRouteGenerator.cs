using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace Htmxor.Generators;

[Generator(LanguageNames.CSharp)]
public sealed class HtmxorRouteGenerator : IIncrementalGenerator
{
	private static readonly DiagnosticDescriptor UnsupportedDeclaration = new(
		"HTMXOR001",
		"Unsupported HTMX-only route declaration",
		"Htmxor supports up to two project-root components without @page; each component must resolve one constrained HtmxRoute with explicit GET-only Methods, no other route filters, and one Authorize policy with compiler-resolved constant values and without roles or authentication schemes",
		"Htmxor.Generators",
		DiagnosticSeverity.Error,
		isEnabledByDefault: true);

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		// Razor and Htmxor generators run in the same unordered pass, so consume the raw Razor input.
		var inputs = context.AdditionalTextsProvider
			.Where(static file => file.Path.EndsWith(".razor", StringComparison.OrdinalIgnoreCase))
			.Select(static (file, cancellationToken) => RazorSourceFile.Read(file, cancellationToken))
			.Collect()
			.Combine(context.CompilationProvider)
			.Combine(context.AnalyzerConfigOptionsProvider);

		context.RegisterSourceOutput(
			inputs,
			static (productionContext, input) => Emit(
				productionContext,
				input.Left.Left,
				input.Left.Right,
				input.Right));
	}

	private static void Emit(
		SourceProductionContext context,
		ImmutableArray<RazorSourceFile> files,
		Compilation compilation,
		AnalyzerConfigOptionsProvider optionsProvider)
	{
		if (files.IsDefaultOrEmpty)
		{
			return;
		}

		var hasProject = TryGetProject(optionsProvider, out var project);
		var declarations = RouteDeclaration.Bind(
			files,
			compilation,
			project.RootNamespace,
			project.ProjectDirectory);
		var orderedDeclarations = declarations
			.OrderBy(static declaration => declaration.ComponentName, StringComparer.Ordinal)
			.ThenBy(static declaration => declaration.Path, StringComparer.Ordinal)
			.ToImmutableArray();
		if (orderedDeclarations.IsDefaultOrEmpty)
		{
			return;
		}

		if (orderedDeclarations.Length > 2 || !hasProject)
		{
			ReportUnsupportedDeclarations(context, orderedDeclarations);
			return;
		}

		var unsupportedDeclarations = orderedDeclarations
			.Where(static declaration => !declaration.IsSupported)
			.ToImmutableArray();
		if (!unsupportedDeclarations.IsDefaultOrEmpty)
		{
			ReportUnsupportedDeclarations(context, unsupportedDeclarations);
			return;
		}

		context.AddSource(
			"HtmxorGeneratedRouteRegistration.g.cs",
			SourceText.From(Render(project.RootNamespace, orderedDeclarations), Encoding.UTF8));
	}

	private static void ReportUnsupportedDeclarations(
		SourceProductionContext context,
		ImmutableArray<RouteDeclaration> declarations)
	{
		foreach (var declaration in declarations)
		{
			context.ReportDiagnostic(Diagnostic.Create(UnsupportedDeclaration, declaration.Location));
		}
	}

	private static bool TryGetProject(
		AnalyzerConfigOptionsProvider optionsProvider,
		out ProjectInput project)
	{
		var options = optionsProvider.GlobalOptions;
		var hasRootNamespace = options.TryGetValue("build_property.RootNamespace", out var rootNamespace);
		var hasProjectDirectory = options.TryGetValue(
			"build_property.MSBuildProjectDirectory",
			out var projectDirectory);
		project = new ProjectInput(rootNamespace ?? string.Empty, projectDirectory ?? string.Empty);

		return hasRootNamespace && hasProjectDirectory;
	}

	private static string Render(
		string rootNamespace,
		ImmutableArray<RouteDeclaration> declarations)
	{
		return "// <auto-generated/>\n" +
			"#nullable enable\n\n" +
			"namespace Microsoft.AspNetCore.Builder;\n\n" +
			"internal static class HtmxorGeneratedRouteRegistrationExtensions\n" +
			"{\n" +
			"\tinternal static global::Microsoft.AspNetCore.Builder.RazorComponentsEndpointConventionBuilder " +
			"AddHtmxorComponentEndpoints(\n" +
			"\t\tthis global::Microsoft.AspNetCore.Builder.RazorComponentsEndpointConventionBuilder builder,\n" +
			"\t\tglobal::Microsoft.AspNetCore.Routing.RouteGroupBuilder endpoints)\n" +
			"\t{\n" +
			"\t\tvar configured = global::Microsoft.AspNetCore.Builder." +
			"HtmxorComponentEndpointRouteBuilderExtensions.AddHtmxorComponentEndpoints(\n" +
			"\t\t\tbuilder,\n" +
			"\t\t\t(global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder)endpoints);\n" +
			string.Concat(declarations.Select(declaration => RenderRegistration(rootNamespace, declaration))) +
			"\n\t\treturn configured;\n" +
			"\t}\n" +
			"}\n";
	}

	private static string RenderRegistration(string rootNamespace, RouteDeclaration declaration)
	{
		var route = EscapeStringLiteral(declaration.Route);
		var policy = EscapeStringLiteral(declaration.Policy);
		return "\t\tglobal::Microsoft.AspNetCore.Builder.HtmxorComponentEndpointRouteBuilderExtensions." +
			"MapHtmxorGeneratedComponentEndpoint(\n" +
			"\t\t\tendpoints,\n" +
			"\t\t\ttypeof(global::" + rootNamespace + "." + declaration.ComponentName + "),\n" +
			"\t\t\t\"" + route + "\",\n" +
			"\t\t\t\"" + policy + "\");\n";
	}

	private static string EscapeStringLiteral(string value)
		=> value
			.Replace("\\", "\\\\")
			.Replace("\"", "\\\"")
			.Replace("\r", "\\r")
			.Replace("\n", "\\n");

	private sealed class ProjectInput(string rootNamespace, string projectDirectory)
	{
		public string RootNamespace { get; } = rootNamespace;

		public string ProjectDirectory { get; } = projectDirectory;
	}
}
